/// Ask the assistant (from ⌘K, with what was typed there).
#[derive(gpui_kit::Action, Clone, PartialEq, Eq, serde::Deserialize)]
#[action(namespace = herse, no_json)]
pub struct AskAgentText(pub String);

/// Open a pasted link (from ⌘K): a notebook on the web, or a live session.
#[derive(gpui_kit::Action, Clone, PartialEq, Eq, serde::Deserialize)]
#[action(namespace = herse, no_json)]
pub struct OpenLinkText(pub String);

/// File ▸ Open Recent ▸ a notebook.
#[derive(gpui_kit::Action, Clone, PartialEq, Eq, serde::Deserialize)]
#[action(namespace = herse, no_json)]
pub struct OpenRecent(pub std::path::PathBuf);

/// ⌘1 … ⌘8 go to that tab; ⌘9 to the last, as in a browser.
#[derive(gpui_kit::Action, Clone, PartialEq, Eq, serde::Deserialize)]
#[action(namespace = herse, no_json)]
pub struct ActivateTab(pub usize);

pub const NOTEBOOK_COMMAND: &str = "NotebookCommand";
pub const NOTEBOOK_EDIT: &str = "NotebookEdit";
/// Edit-mode keys must beat the editor's own bindings (escape, shift-enter),
/// so they bind on the editor node itself, beneath the notebook context.
const IN_EDITOR: &str = "NotebookEdit > Input";
/// The notebook while a text field in an output (an `input()` prompt, a
/// widget) has focus: no cell commands, so keys type.
pub const NOTEBOOK_TEXT: &str = "NotebookText";
pub const WORKSPACE: &str = "Workspace";

pub fn bind_keys(cx: &mut App) {
    let cmd = Some(NOTEBOOK_COMMAND);
    let edit = Some(IN_EDITOR);
    let ws = Some(WORKSPACE);
    cx.bind_keys([
        KeyBinding::new("cmd-q", Quit, None),
        KeyBinding::new("cmd-h", HideApp, None),
        KeyBinding::new("cmd-alt-h", HideOthers, None),
        KeyBinding::new("cmd-m", Minimize, None),
        KeyBinding::new("cmd-o", Open, None),
        KeyBinding::new("cmd-alt-o", OpenFolder, None),
        KeyBinding::new("cmd-n", NewNotebook, None),
        KeyBinding::new("cmd-s", Save, ws),
        KeyBinding::new("cmd-shift-s", SaveAs, ws),
        KeyBinding::new("cmd-w", CloseTab, ws),
        KeyBinding::new("cmd-alt-w", CloseAllTabs, ws),
        KeyBinding::new("ctrl-tab", NextTab, ws),
        KeyBinding::new("ctrl-shift-tab", PrevTab, ws),
        KeyBinding::new("cmd-shift-]", NextTab, ws),
        KeyBinding::new("cmd-shift-[", PrevTab, ws),
        KeyBinding::new("cmd-p", GoToFile, ws),
        KeyBinding::new("cmd-shift-p", CommandPalette, ws),
        KeyBinding::new("cmd-shift-o", GoToHeading, ws),
        KeyBinding::new("cmd-r", GoToHeading, ws),
        KeyBinding::new("cmd-b", ToggleSidebar, ws),
        KeyBinding::new("cmd-shift-e", ToggleOutline, ws),
        KeyBinding::new("cmd-shift-f", FindInWorkspace, ws),
        KeyBinding::new("cmd-=", ZoomIn, ws),
        KeyBinding::new("cmd-+", ZoomIn, ws),
        KeyBinding::new("cmd--", ZoomOut, ws),
        KeyBinding::new("cmd-0", ZoomReset, ws),
        KeyBinding::new("cmd-alt-t", ToggleTheme, ws),
        // The Edit menu's verbs: text in a field, cells in command mode (the
        // deeper bindings win at the keyboard; these label and drive the menu).
        KeyBinding::new("cmd-z", EditUndo, ws),
        KeyBinding::new("cmd-shift-z", EditRedo, ws),
        KeyBinding::new("cmd-x", EditCut, ws),
        KeyBinding::new("cmd-c", EditCopy, ws),
        KeyBinding::new("cmd-v", EditPaste, ws),
        KeyBinding::new("cmd-a", EditSelectAll, ws),
        KeyBinding::new("cmd-,", ShowSettings, ws),
        KeyBinding::new("ctrl-cmd-f", ToggleFullScreen, ws),
        // ⌘K is the command menu, so nothing else starts with it.
        KeyBinding::new("cmd-k", CommandMenu, ws),
        KeyBinding::new("cmd-shift-t", ReopenClosedTab, ws),
        KeyBinding::new("cmd-shift-l", OpenLink, ws),
        KeyBinding::new("cmd-i", AskAgent, ws),
        KeyBinding::new("cmd-alt-right", NextTab, ws),
        KeyBinding::new("cmd-alt-left", PrevTab, ws),
        KeyBinding::new("cmd-1", ActivateTab(0), ws),
        KeyBinding::new("cmd-2", ActivateTab(1), ws),
        KeyBinding::new("cmd-3", ActivateTab(2), ws),
        KeyBinding::new("cmd-4", ActivateTab(3), ws),
        KeyBinding::new("cmd-5", ActivateTab(4), ws),
        KeyBinding::new("cmd-6", ActivateTab(5), ws),
        KeyBinding::new("cmd-7", ActivateTab(6), ws),
        KeyBinding::new("cmd-8", ActivateTab(7), ws),
        KeyBinding::new("cmd-9", ActivateTab(usize::MAX), ws),
        // Command mode: the notebook surface has focus, no editor does.
        KeyBinding::new("down", SelectNext, cmd),
        KeyBinding::new("j", SelectNext, cmd),
        KeyBinding::new("up", SelectPrev, cmd),
        KeyBinding::new("k", SelectPrev, cmd),
        KeyBinding::new("shift-down", ExtendSelectionNext, cmd),
        KeyBinding::new("shift-j", ExtendSelectionNext, cmd),
        KeyBinding::new("shift-up", ExtendSelectionPrev, cmd),
        KeyBinding::new("shift-k", ExtendSelectionPrev, cmd),
        KeyBinding::new("cmd-up", SelectFirst, cmd),
        KeyBinding::new("home", SelectFirst, cmd),
        KeyBinding::new("g g", SelectFirst, cmd),
        KeyBinding::new("cmd-down", SelectLast, cmd),
        KeyBinding::new("end", SelectLast, cmd),
        KeyBinding::new("shift-g", SelectLast, cmd),
        KeyBinding::new("space", PageDown, cmd),
        KeyBinding::new("pagedown", PageDown, cmd),
        KeyBinding::new("shift-space", PageUp, cmd),
        KeyBinding::new("pageup", PageUp, cmd),
        KeyBinding::new("enter", EnterEdit, cmd),
        KeyBinding::new("a", InsertAbove, cmd),
        KeyBinding::new("b", InsertBelow, cmd),
        KeyBinding::new("m", ToMarkdown, cmd),
        KeyBinding::new("y", ToCode, cmd),
        KeyBinding::new("r", ToRaw, cmd),
        KeyBinding::new("d d", DeleteCell, cmd),
        // The Mac's delete keys, as in Finder and VS Code's notebooks.
        // (⌘⌫ last: menus show it.)
        KeyBinding::new("delete", DeleteCell, cmd),
        KeyBinding::new("cmd-backspace", DeleteCell, cmd),
        KeyBinding::new("cmd-d", DuplicateCell, cmd),
        KeyBinding::new("cmd-alt-m", AddComment, cmd),
        KeyBinding::new("shift-/", ShowShortcuts, cmd),
        KeyBinding::new("x", CutCells, cmd),
        KeyBinding::new("c", CopyCells, cmd),
        KeyBinding::new("v", PasteCellsBelow, cmd),
        KeyBinding::new("z", UndoCellOp, cmd),
        KeyBinding::new("shift-z", RedoCellOp, cmd),
        // The Mac's own keys in command mode: cells, unless text is selected.
        KeyBinding::new("cmd-c", CommandCopy, cmd),
        KeyBinding::new("cmd-x", CommandCut, cmd),
        KeyBinding::new("cmd-v", CommandPaste, cmd),
        KeyBinding::new("cmd-z", UndoCellOp, cmd),
        KeyBinding::new("cmd-shift-z", RedoCellOp, cmd),
        KeyBinding::new("cmd-a", SelectAllCells, cmd),
        KeyBinding::new("shift-m", MergeBelow, cmd),
        KeyBinding::new("ctrl-shift-up", MoveCellUp, cmd),
        KeyBinding::new("ctrl-shift-down", MoveCellDown, cmd),
        KeyBinding::new("o", ToggleOutput, cmd),
        KeyBinding::new("escape", StopTyping, Some("NotebookText > Input")),
        KeyBinding::new("l", ToggleLineNumbers, cmd),
        KeyBinding::new("shift-l", ToggleAllLineNumbers, cmd),
        KeyBinding::new("f8", NextError, cmd),
        KeyBinding::new("shift-f8", PrevError, cmd),
        KeyBinding::new("f7", NextChange, cmd),
        KeyBinding::new("shift-f7", PrevChange, cmd),
        KeyBinding::new("left", CollapseSection, cmd),
        KeyBinding::new("right", ExpandSection, cmd),
        KeyBinding::new("cmd-alt-[", CollapseAllHeadings, cmd),
        KeyBinding::new("cmd-alt-]", ExpandAllHeadings, cmd),
        KeyBinding::new("shift-o", ToggleOutputScroll, cmd),
        KeyBinding::new("i i", Interrupt, cmd),
        KeyBinding::new("0 0", Restart, cmd),
        KeyBinding::new("cmd-f", Find, cmd),
        KeyBinding::new("/", Find, cmd),
        KeyBinding::new("escape", Dismiss, cmd),
        // Running works in both modes.
        // The later binding is the one hints show: the Mac's own ⌘↩.
        KeyBinding::new("ctrl-enter", RunCell, cmd),
        KeyBinding::new("cmd-enter", RunCell, cmd),
        KeyBinding::new("shift-enter", RunAndAdvance, cmd),
        KeyBinding::new("alt-enter", RunAndInsert, cmd),
        KeyBinding::new("cmd-shift-a", InsertCodeAbove, ws),
        KeyBinding::new("cmd-shift-b", InsertCodeBelow, ws),
        KeyBinding::new("cmd-shift-m", InsertMarkdownBelow, ws),
        KeyBinding::new("ctrl-enter", RunCell, edit),
        KeyBinding::new("cmd-enter", RunCell, edit),
        KeyBinding::new("shift-enter", RunAndAdvance, edit),
        KeyBinding::new("alt-enter", RunAndInsert, edit),
        KeyBinding::new("escape", ExitEdit, edit),
        KeyBinding::new("cmd-/", ToggleComment, edit),
        KeyBinding::new("alt-up", MoveLineUp, edit),
        KeyBinding::new("alt-down", MoveLineDown, edit),
        KeyBinding::new("cmd-shift-k", DeleteLine, edit),
        KeyBinding::new("alt-shift-up", CopyLineUp, edit),
        KeyBinding::new("alt-shift-down", CopyLineDown, edit),
        KeyBinding::new("cmd-l", SelectLine, edit),
        KeyBinding::new("cmd-alt-m", AddComment, edit),
        KeyBinding::new("ctrl-shift--", SplitCell, edit),
        KeyBinding::new("tab", TabComplete, edit),
        KeyBinding::new("enter", EditorReturn, edit),
        // One history: the cell's typing first, then on into the notebook's.
        KeyBinding::new("cmd-z", EditorUndo, edit),
        KeyBinding::new("cmd-shift-z", EditorRedo, edit),
    ]);
}
